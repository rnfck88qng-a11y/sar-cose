"""Regenerate RESULTS.md from the archived runs (results/runs/) and results/paper_claims.json.

    python3 tools/render_results.py

The summary at the top is rendered from paper_claims.json; each archived run follows with its
record (command, start, duration, load, commit, dirty flag, exit code) and its complete log.
Home-directory paths were already replaced by "~" when the runs were archived.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RUNS = ROOT / "results" / "runs"
ORDER = ["tests", "hand_mutants", "audit_mutants", "concurrency", "stub_gaps", "blind_diff", "vectors_regen", "cddl",
         "vectors", "manifest", "vectors_vs_mutants", "deep", "sweep_sar_cose", "sweep_sar_scitt",
         "bench_1", "bench_2", "bench_3", "bench_4", "bench_5"]


def main():
    c = json.loads((ROOT / "results" / "paper_claims.json").read_text())
    m = c.get("meta", {})
    out = ["# Results (raw output)", "",
           "Generated by `tools/render_results.py` from the machine-readable records in `results/runs/` (one JSON "
           "record and one complete log per run, written by `tools/archive_run.py`) and from "
           "`results/paper_claims.json` (derived from those records by `tools/make_claims.py`). Do not edit by hand.", "",
           f"Code commit of the test run: `{m.get('commit')}` · {m.get('cpu')} ({m.get('cores')} logical cores) · "
           f"{m.get('os')} · Python {m.get('python')} · " +
           " · ".join(f"{k} {v}" for k, v in sorted(m.get("libs", {}).items())), "",
           "## Summary (from results/paper_claims.json)", "", "```", json.dumps(
               {k: c[k] for k in ("tests", "mutants", "sweep", "vectors", "spec", "cddl", "concurrency", "blind_diff",
                                  "scitt", "errors") if k in c}, indent=1, sort_keys=True), "```", ""]
    names = ORDER + sorted(p.stem for p in RUNS.glob("*.json") if p.stem not in ORDER)
    for n in names:
        j = RUNS / f"{n}.json"
        if not j.exists():
            continue
        r = json.loads(j.read_text())
        out += [f"## {n}: `{' '.join(r['command'])}`", "",
                f"started {r['started_utc']} · {r['duration_s']} s · load {r['load_avg_before']} → {r['load_avg_after']} · "
                f"commit `{(r['git_commit'] or '')[:12]}`{' (dirty)' if r['git_dirty'] else ''} · exit {r['exit_code']} · "
                f"{'PASS' if r['passed'] else 'FAIL'}" +
                (f" · env {r['env_overrides']}" if r["env_overrides"] else ""), "", "```",
                (RUNS / f"{n}.log").read_text().rstrip(), "```", ""]
    (ROOT / "RESULTS.md").write_text("\n".join(out) + "\n")
    print(f"wrote RESULTS.md ({len(names)} runs considered)")


if __name__ == "__main__":
    main()
